        message += self.check_range("Clock frequency", f_clk, "f_clk_mhz")
        message += self.check_range("Random clock jitter", sigma_rj, "sigma_rj")
        message += self.check_range("TAC resolution (LSB)", lsb, "lsb")
        message += self.check_range("Duty cycle distortion", dcd, "dcd_pp")
        message += self.check_range("Periodic jitter frequency", pj_freq, "pj_freq_mhz")
        message += self.check_range("Number of events (whole number)", n_events, "n_events")

        if(message != ""):
            # enable signal for correct setting of all the parameters
            return [message.strip(), False]

        else:
            Process_start = timer()
            print("\n## PROCESS RUNNING ##\n")

            # Names on the left are the ones of the PARAMETERS block of
            # tdc_jitter_sim_def.py. Frequencies set in MHz, here are converted in Hz.
            sim.F_CLK = f_clk * 1e6
            sim.T_CLK = 1e12 / sim.F_CLK            # same formula as in the original file
            sim.SIGMA_RJ = sigma_rj
            sim.LSB = lsb
            sim.USE_NEAREST_EDGE = (edge_mode == 1)
            sim.DCD_PP = dcd
            sim.PJ_FREQ = pj_freq * 1e6
            sim.ALPHA_RW = alpha_rw
            sim.PJ_AMP = pj_amp
            sim.INL_AMP = inl_amp
            sim.N_EVENTS = n_events

            # TDC simulation
            print("Simulation processing ...")
            start = timer()
            old_outdir = sim.OUTDIR
            printed = io.StringIO()
            images = {}
            try:
                with tempfile.TemporaryDirectory() as folder:
                    sim.OUTDIR = folder
                    # everything the simulation prints is captured, then shown
                    with contextlib.redirect_stdout(printed):
                        sim.main()
                    for file_name, title, explanation in PLOTS:
                        path = os.path.join(folder, file_name)
                        if os.path.exists(path):
                            with open(path, "rb") as f:
                                images[file_name] = f.read()
            except Exception as error:
                print("## PROCESS FAILED: " + str(error) + " ## \n")
                return ["The simulation failed: " + str(error), False]
            finally:
                sim.OUTDIR = old_outdir
            end = timer()
            print("## TDC SIMULATION COMPLETED AFTER: " + str(round(end - start, 3)) + " s ##\n")

            # numerical report 
            report = re.sub(r"\n*Plots saved in:.*\s*$", "", printed.getvalue())
            print(report + "\n")

            print("Writing the output file...")
            # generate output .txt file with all final results
            now = datetime.datetime.now()
            d_h_format = now.strftime("%Y-%m-%d_%H-%M-%S")
            file_title = os.path.join(SAVE_FOLDER, f"TDC_Simulator_Data_{d_h_format}.txt")

            string_list = []
            string_list.append(f"********TDC_Simulator_Data_{d_h_format}********\n")
            string_list.append("Clock frequency: " + show_number(f_clk) + " MHz\n")
            string_list.append("Random clock jitter (sigma_RJ): " + show_number(sigma_rj) + " ps\n")
            string_list.append("Random-walk share of jitter: " + show_number(round(alpha_rw, 4)) + "\n")
            string_list.append("TAC resolution (LSB): " + show_number(lsb) + " ps\n")
            string_list.append("Clock edges used: " + ("nearest edge (rising or falling)" if edge_mode == 1 else "rising edge only") + "\n")
            string_list.append("Duty cycle distortion (DCD): " + show_number(dcd) + " ps\n")
            if pj_amp != 0:
                string_list.append("Periodic jitter amplitude: " + show_number(pj_amp) + " ps\n")
                string_list.append("Periodic jitter frequency: " + show_number(pj_freq) + " MHz\n")
            else:
                string_list.append("Periodic jitter: off\n")
            if inl_amp != 0:
                string_list.append("TAC non-linearity (INL): " + show_number(inl_amp) + " ps\n")
            else:
                string_list.append("TAC non-linearity (INL): off\n")
            string_list.append("Number of events: " + str(n_events) + "\n")
            string_list.append("\nResults:\n" + report.rstrip() + "\n")

            data_file = ""
            for string in string_list:
                data_file += string

            try:
                os.makedirs(SAVE_FOLDER, exist_ok=True)     # create the folder if it does not exist
                with open(file_title, 'w', encoding="utf-8") as file:
                    file.write(data_file)

                print(f"## DATA WRITTEN IN: {file_title}  ## \n")
            except OSError:
                print("## PROCESS FAILED: could not write in the Data_TDC folder! ## \n")
                return ["Could not write in the Data_TDC folder!", False]

            return [" ", True, images, Process_start, report]


