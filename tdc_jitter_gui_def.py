def show_number(value):
    """Text within a box for parameters/modes configuration."""
    if isinstance(value, int):
        return str(value)
    return str(int(value)) if float(value).is_integer() else f"{value:g}"


def range_text(key):
    """Text next to a box describing available parameter range"""
    lo, hi = RANGES[key]
    return f"allowed: {show_number(lo)} to {show_number(hi)}"


def make_hint(text):
    """Short hints below text boxes."""
    label = QLabel(text)
    label.setWordWrap(True)
    font = label.font()
    font.setPointSize(8)
    label.setFont(font)
    label.setStyleSheet("color: #555555;")
    return label


