class WorkerSignals(QObject):
    '''
    Defines signals available from a running worker thread.

    Supported signals are:
    - started (data returned from starting process)
    - result (object data returned from processing)
    - completed (data returned from completed process)

    '''

    started = pyqtSignal(object)
    result = pyqtSignal(object)
    completed = pyqtSignal(object)


class Worker(QRunnable):
    '''
    Worker thread execution task.

    Inherits from QRunnable to offload heavy computations (e.g., Monte Carlo simulations)
    to a background thread, preventing main GUI from freezing. Communicates status 
    and results back to the GUI thread via a WorkerSignals object.
    '''

    def __init__(self, fn=None, *args, **kwargs):
        super(Worker, self).__init__()

        # Store constructor arguments (re-used for processing)
        self.fn = fn
        self.args = args
        self.kwargs = kwargs
        self.signals = WorkerSignals()

    @pyqtSlot()
    def run(self):
        self.signals.started.emit(self)
        result = self.fn(*self.args, **self.kwargs)
        self.signals.result.emit(result)
        self.signals.completed.emit(self)


class LabelSlider(QWidget):
    """
    Control widget for optional effects in the simulation.

    - Checkbox: toggles noise mechanism on or off. When unchecked, parameter value defaults to 0.
    - Slider: controls normalized integer step (0 to 20). Enabled only when checkbox is checked.
    - Value Scaling: converts slider position to physical parameter value (Value = Position × Scale).
    - Layout: Displays allowed physical range adjacent to the slider alongside an explanation below.

    """
    def __init__(self, label, hint, allowed, scale=1, decimals=0):
        super().__init__()
        self.__scale = scale
        self.__decimals = decimals
        self.__initUi__(label, hint, allowed)

    def __initUi__(self, label, hint, allowed):

        self.__check = QCheckBox()

        self.__text_label = QLabel(label)
        self.__text_label.setText(label)
        my_font = self.__text_label.font()
        my_font.setPointSize(9)
        self.__text_label.setFont(my_font)

        Label_layout = QHBoxLayout()
        Label_layout.setAlignment(Qt.AlignLeft)
        Label_layout.addWidget(self.__check)
        Label_layout.addWidget(self.__text_label)

        self.__slider_value = 0
        self.__slider = QSlider()
        self.__slider.setOrientation(Qt.Horizontal)
        self.__slider.setRange(0, 20)        # default range
        self.__slider.setValue(self.__slider_value)
        self.__slider.valueChanged.connect(self.__valueChanged)
        self.__slider.setSingleStep(1)
        self.__slider.setEnabled(False)

        self.__check.stateChanged.connect(self.toggle_slider)

        self.__zoomLabel = QLabel()
        self.__zoomLabel.setText(self.__shown_text(self.__slider_value))
        self.__zoomLabel.setFixedWidth(self.__zoomLabel.fontMetrics().boundingRect(self.__zoomLabel.text()).width() + 5)

        layout = QVBoxLayout()
        lay_slider = QHBoxLayout()
        lay_slider.setAlignment(Qt.AlignRight | Qt.AlignVCenter)
        lay_slider.addWidget(self.__zoomLabel, Qt.AlignLeft)
        lay_slider.addWidget(self.__slider, Qt.AlignLeft)
        lay_slider.addWidget(QLabel(allowed))
        layout.addLayout(Label_layout)
        layout.addLayout(lay_slider)
        layout.addWidget(make_hint(hint))

        self.setLayout(layout)

    def __shown_text(self, position):
        return f"{position * self.__scale:.{self.__decimals}f}"

    def __valueChanged(self, v):
        self.__zoomLabel.setText(self.__shown_text(v))
        self.__zoomLabel.setFixedWidth(self.__zoomLabel.fontMetrics().boundingRect(
                                         self.__zoomLabel.text()).width() + 5)

    def slider_change(self):
        # Effect-associated value: 0 if the check box is not ticked
        if not self.__check.isChecked():
            return 0.0
        return float(self.__slider.value()) * self.__scale

    def toggle_slider(self, checked):
        # Toggle slider enabled state
        self.__slider.setEnabled(bool(checked))

    def preset(self, checked, position):
        # Check box and the slider starting value/state
        self.__slider.setValue(position)
        self.__check.setChecked(checked)

    def getLabel(self):
        return self.__zoomLabel

    def getSlider(self):
        return self.__slider

    def getSlidervalue(self):
        return self.__slider_value


class PlotPage(QWidget):
    """
    Single-plot window: plot is resized to fit the window; under the plot, 
    the relative description/explanation
    """
    def __init__(self, file_name, explanation):
        super().__init__()
        self.file_name = file_name
        self.raw = None             # bytes of the PNG file
        self.pixmap = None          # same image as whown by Qt

        # Resizing ignored: the image follows the window size instead of
        # forcing the window to the size of the image.
        self.image_label = QLabel("No plot yet.")
        self.image_label.setAlignment(Qt.AlignCenter)
        self.image_label.setSizePolicy(QSizePolicy.Ignored, QSizePolicy.Ignored)
        self.image_label.setMinimumSize(1, 1)

        explain = QLabel(explanation)
        explain.setWordWrap(True)
        save_button = QPushButton("Save image...")
        save_button.clicked.connect(self.save)

        bottom = QHBoxLayout()
        bottom.addWidget(explain, 1)
        bottom.addWidget(save_button, 0, Qt.AlignTop)

        lay = QVBoxLayout(self)
        lay.addWidget(self.image_label, 1)
        lay.addLayout(bottom)

    def set_image(self, raw_bytes):
        self.raw = raw_bytes
        if raw_bytes is None:
            self.pixmap = None
            self.image_label.setText("Image not available.")
            return
        pixmap = QtGui.QPixmap()
        pixmap.loadFromData(raw_bytes, "PNG")
        self.pixmap = pixmap
        self._rescale()

    def _rescale(self):
        if self.pixmap is None or self.pixmap.isNull():
            return
        # Shrink to fit the available area, never enlarge beyond the original.
        size = self.image_label.size().boundedTo(self.pixmap.size())
        self.image_label.setPixmap(self.pixmap.scaled(
            size, Qt.KeepAspectRatio, Qt.SmoothTransformation))

    def resizeEvent(self, event):
        super().resizeEvent(event)
        self._rescale()

    def save(self):
        if self.raw is None:
            QMessageBox.information(self, "Nothing to save", "Run the simulation first.")
            return
        path, _ = QFileDialog.getSaveFileName(self, "Save image", self.file_name,
                                              "PNG image (*.png)")
        if path:
            with open(path, "wb") as f:
                f.write(self.raw)


