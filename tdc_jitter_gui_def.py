    def message_box(self, values):
        """
        Called in the main thread, because windows can only be created there.
        It uses output values from the Worker to open report window + one
        window for each of the 5 plots (alongside its explanation).
        A bool variable is set to generate a Qmessagebox in case of
        wrong set of parameters or failed simulation.

        """
        enable = values[1]

        if(not enable):
            dlg = QMessageBox()
            dlg.setWindowIcon(self.windowIcon())
            dlg.setWindowTitle("Error")
            dlg.setText(values[0])
            dlg.exec()
            self.runButton.setText("Run")
            self.runButton.setEnabled(True)
        else:

            print("Filling the output plots ...")
            start = timer()
            images = values[2]
            report = values[4]

            if self.report_window is None:
                self.report_window = ReportWindow()
            self.report_window.update_results(report)
            self.report_window.show()
            self.report_window.raise_()

            # One window for each plot. The windows are created, then reused 
